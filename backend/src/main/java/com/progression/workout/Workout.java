package com.progression.workout;

import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.UUID;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import jakarta.persistence.Version;

/**
 * A training session, and the <em>aggregate root</em> for its exercises and
 * sets: they are only ever loaded, saved and deleted through their workout
 * (cascade + orphan removal), which keeps the whole session consistent.
 *
 * <p>The owner is stored as a plain {@code userId} rather than a JPA
 * relationship to {@code AppUser}. Workouts never need to load the user, and
 * keeping aggregates independent avoids accidental cross-aggregate loading.
 */
@Entity
@Table(name = "workout")
public class Workout {

	/** Assigned by the client (see ADR 0003), never generated by the database. */
	@Id
	private UUID id;

	@Column(nullable = false, updatable = false)
	private UUID userId;

	@Column(nullable = false)
	private String name;

	@Column(nullable = false)
	private Instant startedAt;

	private Instant endedAt;

	private String notes;

	/** Client-reported modification time, used for last-write-wins conflict detection. */
	@Column(nullable = false)
	private Instant updatedAt;

	/**
	 * Optimistic-locking counter. Also tells Spring Data whether the entity is new:
	 * {@code null} means "not yet persisted", even though the id is already set.
	 */
	@Version
	private Long version;

	@OneToMany(mappedBy = "workout", cascade = CascadeType.ALL, orphanRemoval = true)
	@OrderBy("position ASC")
	private List<WorkoutExercise> exercises = new ArrayList<>();

	protected Workout() {
	}

	Workout(UUID id, UUID userId) {
		this.id = id;
		this.userId = userId;
	}

	void updateDetails(String name, Instant startedAt, Instant endedAt, String notes, Instant updatedAt) {
		this.name = name;
		this.startedAt = startedAt;
		this.endedAt = endedAt;
		this.notes = notes;
		this.updatedAt = updatedAt;
	}

	/**
	 * Replaces the exercise list. The collection instance is reused rather than
	 * swapped, because Hibernate tracks orphan removal on the original collection:
	 * any exercise not in {@code replacement} is deleted on flush.
	 */
	void replaceExercises(List<WorkoutExercise> replacement) {
		exercises.clear();
		exercises.addAll(replacement);
	}

	public UUID getId() {
		return id;
	}

	public UUID getUserId() {
		return userId;
	}

	public String getName() {
		return name;
	}

	public Instant getStartedAt() {
		return startedAt;
	}

	public Instant getEndedAt() {
		return endedAt;
	}

	public String getNotes() {
		return notes;
	}

	public Instant getUpdatedAt() {
		return updatedAt;
	}

	public boolean isNew() {
		return version == null;
	}

	public List<WorkoutExercise> getExercises() {
		return Collections.unmodifiableList(exercises);
	}
}
