-- One row per identity-provider user, created just-in-time on their first API call.
CREATE TABLE app_user (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    cognito_sub  text        NOT NULL UNIQUE,
    email        text,
    display_name text        CHECK (length(display_name) <= 50),
    weight_unit  text        NOT NULL DEFAULT 'LB' CHECK (weight_unit IN ('LB', 'KG')),
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- Exercise definitions. owner_id NULL = built-in catalog shared by all users;
-- otherwise a custom exercise visible only to its owner.
CREATE TABLE exercise (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id     uuid        REFERENCES app_user (id) ON DELETE CASCADE,
    name         text        NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    muscle_group text        NOT NULL,
    equipment    text        NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- Names are unique case-insensitively, separately for the catalog and per owner.
-- (Two partial indexes because NULL owner_ids never collide in a plain unique index.)
CREATE UNIQUE INDEX exercise_catalog_name_uq ON exercise (lower(name)) WHERE owner_id IS NULL;
CREATE UNIQUE INDEX exercise_owner_name_uq   ON exercise (owner_id, lower(name)) WHERE owner_id IS NOT NULL;

-- A training session. The id is generated by the mobile app so workouts can be
-- created offline and saved idempotently (ADR 0003).
CREATE TABLE workout (
    id          uuid        PRIMARY KEY,
    user_id     uuid        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    name        text        NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    started_at  timestamptz NOT NULL,
    ended_at    timestamptz,
    notes       text,
    -- Client-reported modification time, used for last-write-wins conflict detection.
    updated_at  timestamptz NOT NULL,
    -- JPA optimistic-locking counter, guards against concurrent server-side writes.
    version     bigint      NOT NULL DEFAULT 0,
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- History list: a user's workouts, newest first, with id as a tiebreaker for cursors.
CREATE INDEX workout_user_started_idx ON workout (user_id, started_at DESC, id DESC);

-- One exercise performed within one workout, in display order.
CREATE TABLE workout_exercise (
    id          uuid   PRIMARY KEY,
    workout_id  uuid   NOT NULL REFERENCES workout (id) ON DELETE CASCADE,
    exercise_id uuid   NOT NULL REFERENCES exercise (id),
    position    int    NOT NULL CHECK (position >= 0),
    notes       text,
    version     bigint NOT NULL DEFAULT 0
);

CREATE INDEX workout_exercise_workout_idx  ON workout_exercise (workout_id);
-- "Last time you did this exercise" and per-exercise progression charts.
CREATE INDEX workout_exercise_exercise_idx ON workout_exercise (exercise_id, workout_id);

-- A single set: weight x reps.
CREATE TABLE exercise_set (
    id                  uuid         PRIMARY KEY,
    workout_exercise_id uuid         NOT NULL REFERENCES workout_exercise (id) ON DELETE CASCADE,
    position            int          NOT NULL CHECK (position >= 0),
    set_type            text         NOT NULL CHECK (set_type IN ('WARMUP', 'WORKING', 'DROP', 'FAILURE')),
    -- Stored exactly as the user entered it, so 185 lb never displays as 184.99.
    weight              numeric(7,2) NOT NULL CHECK (weight >= 0),
    weight_unit         text         NOT NULL CHECK (weight_unit IN ('LB', 'KG')),
    -- Normalized copy maintained by PostgreSQL. Analytics use this so that
    -- history logged in mixed units compares correctly.
    weight_kg           numeric(8,3) GENERATED ALWAYS AS (
                            CASE WHEN weight_unit = 'LB' THEN weight * 0.45359237 ELSE weight END
                        ) STORED,
    reps                int          NOT NULL CHECK (reps BETWEEN 0 AND 1000),
    rpe                 numeric(3,1) CHECK (rpe BETWEEN 1 AND 10),
    completed_at        timestamptz,
    version             bigint       NOT NULL DEFAULT 0
);

CREATE INDEX exercise_set_workout_exercise_idx ON exercise_set (workout_exercise_id);
